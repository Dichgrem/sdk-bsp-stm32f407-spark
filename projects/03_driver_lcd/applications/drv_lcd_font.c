void lcd_draw_hz16(int x, int y, const uint8_t glyph[32]) {
  for (int row = 0; row < 16; ++row) {
    uint8_t hi = glyph[row * 2];
    uint8_t lo = glyph[row * 2 + 1];

    for (int col = 0; col < 8; ++col) {
      if (hi & (1u << (7 - col))) {
        lcd_draw_point(x + col, y + row);
      }
    }

    for (int col = 0; col < 8; ++col) {
      if (lo & (1u << (7 - col))) {
        lcd_draw_point(x + 8 + col, y + row);
      }
    }
  }
}
